#!/usr/bin/env python3
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[2]
SOURCE_PATH = Path("tools/codegen/languages.json")
OUTPUT_PATH = Path("app/src/main/java/com/astracode/app/GeneratedLanguageCompletions.kt")
TOKEN_PATTERN = re.compile(r"[A-Za-z_$][A-Za-z0-9_$-]*\Z")


class CodegenError(ValueError):
    pass


def _reject_duplicate_keys(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
    result: dict[str, Any] = {}
    for key, value in pairs:
        if key in result:
            raise CodegenError(f"duplicate JSON key: {key}")
        result[key] = value
    return result


def normalize_catalog(data: Any) -> dict[str, list[str]]:
    if not isinstance(data, dict) or data.get("schemaVersion") != 1:
        raise CodegenError("language catalog must use schemaVersion 1")
    if set(data) != {"schemaVersion", "languages"}:
        raise CodegenError("language catalog must contain only schemaVersion and languages")

    raw_languages = data.get("languages")
    if not isinstance(raw_languages, dict) or not raw_languages:
        raise CodegenError("languages must be a non-empty object")

    normalized: dict[str, list[str]] = {}
    for language, raw_tokens in raw_languages.items():
        if not isinstance(language, str) or not language.strip() or language != language.strip():
            raise CodegenError("language names must be non-empty, trimmed strings")
        if len(language) > 64 or any(ord(char) < 32 for char in language):
            raise CodegenError(f"invalid language name: {language!r}")
        if not isinstance(raw_tokens, list) or not raw_tokens:
            raise CodegenError(f"{language}: completion tokens must be a non-empty array")

        tokens: list[str] = []
        seen: set[str] = set()
        for token in raw_tokens:
            if not isinstance(token, str) or not TOKEN_PATTERN.fullmatch(token):
                raise CodegenError(f"{language}: invalid completion token: {token!r}")
            if len(token) > 128:
                raise CodegenError(f"{language}: completion token is too long: {token[:32]!r}")
            if token not in seen:
                seen.add(token)
                tokens.append(token)
        normalized[language] = tokens

    return normalized


def load_catalog(path: Path) -> dict[str, list[str]]:
    try:
        data = json.loads(path.read_text(encoding="utf-8"), object_pairs_hook=_reject_duplicate_keys)
    except OSError as error:
        raise CodegenError(f"cannot read {path}: {error}") from error
    except json.JSONDecodeError as error:
        raise CodegenError(f"invalid JSON in {path}: {error}") from error
    return normalize_catalog(data)


def _kotlin_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("$", r"\$")


def render_kotlin(languages: dict[str, list[str]]) -> str:
    lines = [
        "package com.astracode.app",
        "",
        "// Generated by tools/codegen/generate_language_completions.py. Do not edit by hand.",
        "",
        "internal val LANGUAGE_COMPLETIONS: Map<String, Set<String>> = linkedMapOf(",
    ]
    for language, tokens in languages.items():
        lines.append(f"    {_kotlin_string(language)} to setOf(")
        for offset in range(0, len(tokens), 6):
            chunk = tokens[offset : offset + 6]
            lines.append("        " + ", ".join(_kotlin_string(token) for token in chunk) + ",")
        lines.append("    ),")
    lines.extend([")", ""])
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the editor's offline language completion catalog.")
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--check", action="store_true", help="fail if the generated Kotlin file is out of date")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    source = root / SOURCE_PATH
    output = root / OUTPUT_PATH
    try:
        generated = render_kotlin(load_catalog(source))
    except CodegenError as error:
        print(f"code generation failed: {error}", file=sys.stderr)
        return 2

    if args.check:
        try:
            current = output.read_text(encoding="utf-8")
        except OSError:
            current = ""
        if current != generated:
            print(f"{OUTPUT_PATH.as_posix()} is out of date; run the generator without --check", file=sys.stderr)
            return 1
        print("Language completion catalog is up to date.")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(generated, encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT_PATH.as_posix()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
